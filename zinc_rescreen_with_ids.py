"""
Re-screen the ZINC subset while PRESERVING actual compound IDs and provenance.

This script uses the ensemble of PI-EGNN checkpoints generated by
03_repeated_scaffold_validation.py. It records:
- actual ZINC ID from each .smi line,
- SMILES,
- source URL,
- tranche identifier parsed from the URL,
- URI-list position,
- ensemble mean active probability,
- ensemble SD across repeated scaffold models.

Selection is deterministic: the first MAX_VALID_MOLECULES valid, unique molecules
encountered from the ordered URI list. This makes the revised subset exactly
reproducible. Change MAX_VALID_MOLECULES only if you intend to change the
screening-library size.
"""
from pathlib import Path
import gzip
import urllib.request
import re
import numpy as np
import pandas as pd
from rdkit import Chem

from revision_config import CFG
from revision_core import ensure_dir, mol_to_graph, PIEGNN, HAS_PYG

if not HAS_PYG:
    raise ImportError("torch and torch-geometric are required.")

import torch
from torch_geometric.loader import DataLoader

OUT = Path(CFG.outdir) / "05b_zinc_rescreen"
CKPT_DIR = Path(CFG.outdir) / "03_repeated_validation"
ensure_dir(OUT)

MAX_VALID_MOLECULES = 49999
DOWNLOAD_TIMEOUT = 120
BATCH_SIZE = 256

def canonicalize(s):
    m = Chem.MolFromSmiles(str(s))
    if m is None:
        return None
    return Chem.MolToSmiles(m, canonical=True, isomericSmiles=True)

def read_uri_list():
    with open(CFG.zinc_uri, "r", encoding="utf-8") as f:
        return [x.strip() for x in f if x.strip()]

def download_text(url):
    with urllib.request.urlopen(url, timeout=DOWNLOAD_TIMEOUT) as r:
        raw = r.read()
    if url.lower().endswith(".gz"):
        raw = gzip.decompress(raw)
    return raw.decode("utf-8", errors="ignore")

def tranche_from_url(url):
    # e.g. .../2D/AA/AAAA.smi -> AA/AAAA
    parts = url.rstrip("/").split("/")
    if len(parts) >= 2:
        return "/".join(parts[-2:]).replace(".smi.gz", "").replace(".smi", "")
    return ""

def collect_subset():
    urls = read_uri_list()
    rows = []
    seen = set()
    for ui, url in enumerate(urls):
        if len(rows) >= MAX_VALID_MOLECULES:
            break
        print(f"Downloading URI {ui+1}/{len(urls)}: {url}")
        try:
            text = download_text(url)
        except Exception as e:
            print("  download failed:", e)
            continue
        tranche = tranche_from_url(url)
        for line_no, line in enumerate(text.splitlines(), 1):
            if len(rows) >= MAX_VALID_MOLECULES:
                break
            parts = line.strip().split()
            if len(parts) < 2:
                continue
            smi = canonicalize(parts[0])
            if smi is None or smi in seen:
                continue
            zinc_id = parts[1]
            seen.add(smi)
            rows.append({
                "zinc_id": zinc_id,
                "smiles": smi,
                "source_url": url,
                "tranche": tranche,
                "uri_list_index": ui,
                "source_line_number": line_no,
            })
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "zinc_revision_subset_with_ids.csv", index=False)
    return df

def load_ensemble(sample_graph):
    ckpts = sorted(CKPT_DIR.glob("PI_EGNN_seed*.pt"))
    if not ckpts:
        raise FileNotFoundError(
            f"No PI_EGNN_seed*.pt checkpoints found in {CKPT_DIR}. "
            "Run 03_repeated_scaffold_validation.py first."
        )
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    models = []
    for p in ckpts:
        ck = torch.load(p, map_location=device)
        cc = ck.get("config", {})
        model = PIEGNN(
            node_dim=sample_graph.x.size(-1),
            edge_dim=sample_graph.edge_attr.size(-1),
            path_dim=sample_graph.path_attr.size(-1),
            hidden_dim=int(cc.get("hidden_dim", CFG.hidden_dim)),
            layers=int(cc.get("layers", CFG.layers)),
            dropout=float(cc.get("dropout", CFG.dropout)),
            task="classification",
            path_mode=ck.get("path_mode", "learned"),
        )
        model.load_state_dict(ck["model_state"])
        model.to(device).eval()
        models.append((p.name, model))
    return models, device

def score(df):
    graphs = []
    keep = []
    for i, s in enumerate(df["smiles"]):
        g = mol_to_graph(s, y_cls=0, max_path_len=CFG.max_path_len)
        if g is not None:
            graphs.append(g)
            keep.append(i)
    if not graphs:
        raise RuntimeError("No valid ZINC graphs.")

    models, device = load_ensemble(graphs[0])
    loader = DataLoader(graphs, batch_size=BATCH_SIZE, shuffle=False)
    all_model_scores = [[] for _ in models]

    with torch.no_grad():
        for batch in loader:
            batch = batch.to(device)
            for mi, (_, model) in enumerate(models):
                prob = torch.sigmoid(model(batch)).cpu().numpy()
                all_model_scores[mi].extend(prob.tolist())

    S = np.asarray(all_model_scores, dtype=float).T
    scored = df.iloc[keep].reset_index(drop=True).copy()
    scored["PI_EGNN_ensemble_mean"] = S.mean(axis=1)
    scored["PI_EGNN_ensemble_sd"] = S.std(axis=1, ddof=1) if S.shape[1] > 1 else 0.0
    scored["n_ensemble_models"] = S.shape[1]
    for mi, (name, _) in enumerate(models):
        scored[f"prob_{Path(name).stem}"] = S[:, mi]

    scored = scored.sort_values(
        ["PI_EGNN_ensemble_mean", "PI_EGNN_ensemble_sd"],
        ascending=[False, True]
    ).reset_index(drop=True)
    scored["ensemble_rank"] = np.arange(1, len(scored) + 1)
    scored.to_csv(OUT / "zinc_revision_screened_with_ids.csv", index=False)
    scored.head(500).to_csv(OUT / "zinc_revision_top500_with_ids.csv", index=False)
    return scored

def main():
    subset_file = OUT / "zinc_revision_subset_with_ids.csv"
    if subset_file.exists():
        subset = pd.read_csv(subset_file)
        print("Using existing deterministic subset:", subset_file)
    else:
        subset = collect_subset()
    print("Valid unique molecules collected:", len(subset))
    scored = score(subset)
    print(scored.head(20)[[
        "ensemble_rank", "zinc_id", "smiles",
        "PI_EGNN_ensemble_mean", "PI_EGNN_ensemble_sd",
        "tranche", "source_url"
    ]].to_string(index=False))

if __name__ == "__main__":
    main()
